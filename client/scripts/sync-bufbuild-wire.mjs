/**
 * Sync a Cocos-safe subset of @bufbuild/protobuf wire into assets as TypeScript.
 *
 * Why not copy node_modules ESM .js?
 * - Cocos treats assets/*.js as CJS plugins → "Unexpected export statement in CJS module"
 *
 * Why a subset?
 * - Generated pitaya TS only needs BinaryReader / BinaryWriter (binary-encoding).
 * - Full wire/index also exports text-format / size-delimited, which pull the whole package.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const clientRoot = path.resolve(__dirname, '..')
const srcRoot = path.join(clientRoot, 'node_modules', '@bufbuild', 'protobuf', 'dist', 'esm')
const destRoot = path.join(clientRoot, 'assets', 'platform', 'vendor', 'bufbuild-protobuf')

/** Files required for BinaryReader / BinaryWriter */
const WIRE_FILES = [
  'binary-encoding.js',
  'base64-encoding.js',
  'text-encoding.js',
  'varint.js',
]

function toTsSource(js) {
  return js.replace(/from\s+["'](\.[^"']+)\.js["']/g, 'from "$1"')
}

function writeTs(relJs) {
  const from = path.join(srcRoot, relJs)
  if (!fs.existsSync(from)) throw new Error(`missing: ${from}`)
  const relTs = relJs.replace(/\.js$/, '.ts')
  const to = path.join(destRoot, relTs)
  fs.mkdirSync(path.dirname(to), { recursive: true })
  fs.writeFileSync(to, toTsSource(fs.readFileSync(from, 'utf8')), 'utf8')
}

if (!fs.existsSync(srcRoot)) {
  console.error('[sync-bufbuild-wire] run npm install first (missing @bufbuild/protobuf)')
  process.exit(1)
}

fs.rmSync(destRoot, { recursive: true, force: true })
fs.mkdirSync(path.join(destRoot, 'wire'), { recursive: true })

for (const name of WIRE_FILES) {
  writeTs(path.join('wire', name))
}
writeTs('proto-int64.js')

// Minimal public surface (matches what generated proto imports)
fs.writeFileSync(
  path.join(destRoot, 'wire', 'index.ts'),
  [
    '// Auto-generated by scripts/sync-bufbuild-wire.mjs — do not edit.',
    'export * from "./binary-encoding";',
    'export * from "./base64-encoding";',
    'export * from "./text-encoding";',
    '',
  ].join('\n'),
  'utf8',
)

fs.writeFileSync(
  path.join(destRoot, 'README.txt'),
  [
    'Auto-synced subset of @bufbuild/protobuf for Cocos (npm run sync:wire).',
    'Import Map: @bufbuild/protobuf/wire → wire/index.ts',
    'Provides BinaryReader / BinaryWriter only.',
    '',
  ].join('\n'),
  'utf8',
)

console.log('[sync-bufbuild-wire] synced TS subset ->', path.relative(clientRoot, destRoot))
