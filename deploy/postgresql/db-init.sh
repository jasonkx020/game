#!/usr/bin/env bash
# GameS first-time PostgreSQL bootstrap: create app role + database(s).
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=read-postgres-config.sh
source "$SCRIPT_DIR/read-postgres-config.sh" --load

SCOPE=""
SPLIT_AUTH=0
WRITE_ENV_FLAG=0
NO_WRITE_ENV=0
APP_PASSWORD_OVERRIDE=""

usage() {
  cat <<EOF
Usage: $0 [game|auth|all] [--split-auth] [--write-env|--no-write-env] [--app-password PASS]

Creates GameS app role + database(s) using config.ini.
Superuser password empty (default) uses local socket / peer trust.
EOF
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    game|auth|all) SCOPE="$1"; shift ;;
    --split-auth) SPLIT_AUTH=1; shift ;;
    --write-env) WRITE_ENV_FLAG=1; shift ;;
    --no-write-env) NO_WRITE_ENV=1; shift ;;
    --app-password) APP_PASSWORD_OVERRIDE="$2"; shift 2 ;;
    -h|--help) usage; exit 0 ;;
    *) echo "unknown arg: $1" >&2; usage; exit 1 ;;
  esac
done

if [[ -z "$SCOPE" ]]; then
  SCOPE="${DEFAULT_SCOPE:-game}"
fi
if [[ "$SPLIT_AUTH" -eq 1 && -z "${POSTGRES_DB_AUTH:-}" ]]; then
  POSTGRES_DB_AUTH=auth
fi

if [[ -n "$APP_PASSWORD_OVERRIDE" ]]; then
  POSTGRES_PASSWORD="$APP_PASSWORD_OVERRIDE"
fi

gen_password() {
  LC_ALL=C tr -dc 'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789' </dev/urandom | head -c 24
}

sql_escape() {
  printf '%s' "$1" | sed "s/'/''/g"
}

uri_escape() {
  python3 -c 'import urllib.parse,sys; print(urllib.parse.quote(sys.argv[1], safe=""))' "$1" 2>/dev/null \
    || printf '%s' "$1" | sed 's/%/%25/g; s/:/%3A/g; s/@/%40/g; s/\//%2F/g; s/#/%23/g; s/?/%3F/g; s/&/%26/g; s/=/%3D/g; s/ /%20/g'
}

if [[ -z "$PSQL_EXE" || ! -x "$PSQL_EXE" ]]; then
  echo "[ERROR] psql not found. Set install_path in config.ini or install client tools." >&2
  exit 1
fi

if [[ -z "$POSTGRES_PASSWORD" ]]; then
  POSTGRES_PASSWORD="$(gen_password)"
  echo "Generated Application password (saved to postgres.env)."
fi

DO_GAME=0
DO_AUTH=0
case "$SCOPE" in
  game) DO_GAME=1 ;;
  auth)
    DO_AUTH=1
    if [[ -z "${POSTGRES_DB_AUTH:-}" ]]; then
      echo "[ERROR] Scope=auth requires Application.db_auth or --split-auth" >&2
      exit 1
    fi
    ;;
  all)
    DO_GAME=1
    if [[ -n "${POSTGRES_DB_AUTH:-}" ]]; then
      DO_AUTH=1
    fi
    ;;
esac

PASS_SQL="$(sql_escape "$POSTGRES_PASSWORD")"
ROLE_SQL="$(sql_escape "$POSTGRES_USER")"

SQL=$(cat <<EOF
DO \$\$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${ROLE_SQL}') THEN
    CREATE ROLE ${POSTGRES_USER} LOGIN PASSWORD '${PASS_SQL}';
  ELSE
    ALTER ROLE ${POSTGRES_USER} WITH LOGIN PASSWORD '${PASS_SQL}';
  END IF;
END
\$\$;
EOF
)

if [[ "$DO_GAME" -eq 1 ]]; then
  SQL+=$(cat <<EOF

SELECT format('CREATE DATABASE %I OWNER %I', '${POSTGRES_DB}', '${POSTGRES_USER}')
WHERE NOT EXISTS (SELECT 1 FROM pg_database WHERE datname = '${POSTGRES_DB}')\gexec
GRANT ALL PRIVILEGES ON DATABASE ${POSTGRES_DB} TO ${POSTGRES_USER};
ALTER DATABASE ${POSTGRES_DB} OWNER TO ${POSTGRES_USER};
EOF
)
fi

if [[ "$DO_AUTH" -eq 1 ]]; then
  SQL+=$(cat <<EOF

SELECT format('CREATE DATABASE %I OWNER %I', '${POSTGRES_DB_AUTH}', '${POSTGRES_USER}')
WHERE NOT EXISTS (SELECT 1 FROM pg_database WHERE datname = '${POSTGRES_DB_AUTH}')\gexec
GRANT ALL PRIVILEGES ON DATABASE ${POSTGRES_DB_AUTH} TO ${POSTGRES_USER};
ALTER DATABASE ${POSTGRES_DB_AUTH} OWNER TO ${POSTGRES_USER};
EOF
)
fi

SCHEMA_SQL=$(cat <<EOF
GRANT ALL ON SCHEMA public TO ${POSTGRES_USER};
ALTER SCHEMA public OWNER TO ${POSTGRES_USER};
EOF
)

run_admin_psql() {
  local db="$1" file="$2"
  local args=(-v ON_ERROR_STOP=1 -U "$POSTGRES_SUPERUSER" -d "$db" -f "$file")
  if [[ -n "$POSTGRES_SUPERUSER_PASSWORD" ]]; then
    export PGPASSWORD="$POSTGRES_SUPERUSER_PASSWORD"
    echo "Connecting ${POSTGRES_SUPERUSER}@${POSTGRES_HOST}:${PG_PORT} db=$db ..."
    "$PSQL_EXE" -h "$POSTGRES_HOST" -p "$PG_PORT" "${args[@]}"
  else
    unset PGPASSWORD || true
    echo "Connecting ${POSTGRES_SUPERUSER} via local socket (no password) db=$db ..."
    "$PSQL_EXE" "${args[@]}"
  fi
}

TMP="$(mktemp)"
TMP_SCHEMA="$(mktemp)"
trap 'rm -f "$TMP" "$TMP_SCHEMA"' EXIT
printf '%s\n' "$SQL" >"$TMP"
printf '%s\n' "$SCHEMA_SQL" >"$TMP_SCHEMA"

run_admin_psql postgres "$TMP"
if [[ "$DO_GAME" -eq 1 ]]; then
  run_admin_psql "$POSTGRES_DB" "$TMP_SCHEMA"
fi
if [[ "$DO_AUTH" -eq 1 ]]; then
  run_admin_psql "$POSTGRES_DB_AUTH" "$TMP_SCHEMA"
fi

AUTH_DB_NAME="${POSTGRES_DB_AUTH:-$POSTGRES_DB}"
USER_ENC="$(uri_escape "$POSTGRES_USER")"
PASS_ENC="$(uri_escape "$POSTGRES_PASSWORD")"
GAME_DSN="postgres://${USER_ENC}:${PASS_ENC}@${POSTGRES_HOST}:${PG_PORT}/${POSTGRES_DB}?sslmode=disable"
AUTH_DSN="postgres://${USER_ENC}:${PASS_ENC}@${POSTGRES_HOST}:${PG_PORT}/${AUTH_DB_NAME}?sslmode=disable"

OUT_ENV="$SCRIPT_DIR/postgres.env"
cat >"$OUT_ENV" <<EOF
# Generated by deploy/postgresql/db-init.sh — do not commit
POSTGRES_HOST=$POSTGRES_HOST
POSTGRES_HOST_PORT=$PG_PORT
POSTGRES_SUPERUSER=$POSTGRES_SUPERUSER
POSTGRES_SUPERUSER_PASSWORD=$POSTGRES_SUPERUSER_PASSWORD
POSTGRES_USER=$POSTGRES_USER
POSTGRES_PASSWORD=$POSTGRES_PASSWORD
POSTGRES_DB=$POSTGRES_DB
POSTGRES_DB_AUTH=$POSTGRES_DB_AUTH
DATABASE_URL=$GAME_DSN
AUTH_DATABASE_URL=$AUTH_DSN
EOF
echo "Wrote $OUT_ENV"

upsert_env() {
  local file="$1" key="$2" val="$3" dir example
  dir="$(dirname "$file")"
  mkdir -p "$dir"
  if [[ ! -f "$file" ]]; then
    example="$dir/.env.example"
    if [[ -f "$example" ]]; then
      cp "$example" "$file"
    else
      : >"$file"
    fi
  fi
  awk -v k="$key" -v v="$val" '
    BEGIN { done = 0 }
    index($0, k "=") == 1 { print k "=" v; done = 1; next }
    { print }
    END { if (!done) print k "=" v }
  ' "$file" >"${file}.tmp"
  mv "${file}.tmp" "$file"
}

SHOULD_WRITE=0
if [[ "$WRITE_ENV_FLAG" -eq 1 ]]; then
  SHOULD_WRITE=1
elif [[ "$NO_WRITE_ENV" -eq 0 && ("$WRITE_ENV" == "true" || "$WRITE_ENV" == "1" || "$WRITE_ENV" == "yes") ]]; then
  SHOULD_WRITE=1
fi

if [[ "$SHOULD_WRITE" -eq 1 ]]; then
  upsert_env "$REPO_ROOT/server/.env" DATABASE_URL "$GAME_DSN"
  upsert_env "$REPO_ROOT/auth-service/.env" DATABASE_URL "$AUTH_DSN"
  echo "Updated server/.env and auth-service/.env DATABASE_URL"
fi

echo ""
echo "Done. Next (from repo root):"
echo "  make seed-dev"
echo "  make run-auth"
echo "DSN (game): $GAME_DSN"
if [[ -n "${POSTGRES_DB_AUTH:-}" ]]; then
  echo "DSN (auth): $AUTH_DSN"
fi
